// cn_font.c - In-game Chinese (iQue/CN) glyph rendering support.
//
// SM64's in-game font renderer (render_generic_char) is single-byte: it indexes
// main_font_lut[c] with an 8-bit char code and draws an 8x16 tile through the
// shared dl_ia_text_tex_settings display list. The iQue/CN release instead
// encodes text as two-byte sequences (0x01-0x05 lead byte + low byte), and CJK
// glyphs are full-width, so we need a separate glyph path.
//
// Glyph data (the real thing)
// ---------------------------
// The iQue ROM stores every CJK glyph inside segment2 (an MIO0-compressed
// segment) as two 16-byte tiles:
//
//   code 0x0100 + n  ->  left  half at segment2 offset 0x16880 + n*0x20
//                        right half at segment2 offset 0x16880 + n*0x20 + 0x10
//
// This is not guesswork: the decomp's CN font LUT holds entries named after
// exactly those offsets (texture_font_char_cn_16880, _16890, _168A0, ... spaced
// 0x10 apart) and ingame_menu.c's CN branch walks them two at a time:
//
//     strChar = (strChar - 0xFF) * 2 + 0xFE;      // codepoint -> LUT index
//     render_generic_char_cn(strChar);      x += 8;
//     render_generic_char_cn(strChar + 1);  x += 8;
//
// Each tile is a 16-column x 8-row bitmap, and the CN vertex_ia8_char in
// bin/segment2.c transposes it: s (0..512) runs along the quad's y and t
// (256..0) along its x, so the drawn half is `half[y][x] = tile[7 - x][y]`.
// The two mirrored halves sit side by side to make the 16x16 cell.
//
// A previous revision stacked the tiles vertically and rotated 90 degrees
// clockwise. That also produces 16x16 pictures, and single tiles like 三 happen
// to look plausible either way, but it is wrong: ！ came out as a hollow
// rectangle and 。's circle landed in the wrong corner. 三 (three bars),
// ！ (stem + dot), 。 (circle), 的 (白+勺), 我 (扌+戈) and 积 (禾+只) all read
// correctly only under the transpose above.
//
// We bake the 1072 glyphs (codes 0x0100..0x052F) into cn_data/cn_glyphs_16x16.h
// as 16x16 1bpp, row-major MSb-first, 32 bytes per glyph, addressed by
// codepoint. At runtime we expand the requested glyph into an IA8 tile and hand
// it to our own CJK-sized display list.
//
// The ASCII path cannot be reused directly: dl_ia_text_tex_settings hardcodes an
// 16x8 load block and its own quad, which is the wrong shape for a 16x16 glyph.
// We therefore keep our own display list (sCnTextTexSettings) sized for the CJK
// tile, and pick the IA8 (not 16b) source format to match our decoded data.

#include <ultra64.h>
#include <string.h>

#include "types.h"
#include "macros.h"
#include "ingame_menu.h"
#include "segment2.h"
#include "cn_font.h"
#include "pc/djui/djui_font.h"

