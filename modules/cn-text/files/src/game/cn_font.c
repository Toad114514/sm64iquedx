// --- Glyph geometry ---------------------------------------------------------
// One glyph is 16x16 (full-width CJK cell).
// CN_GLYPH_W / CN_GLYPH_H now live in cn_font.h: callers outside this file need
// the cell height to convert between the menu Y axis (up) and the HUD/rectangle
// one (down). Defining them again here would risk the two drifting apart.
#define CN_GLYPH_PITCH 16      // 16 pixels = 2 bytes per row (1bpp)
#define CN_GLYPH_STRIDE 2

// --- Decoded glyph tiles ----------------------------------------------------
// IA8 on the N64 is I4A4: *one* byte per texel (4 bits intensity, 4 bits
// alpha). See import_texture_ia8() in src/pc/gfx/gfx_pc.c, which reads
// `addr[i] >> 4` and `addr[i] & 0xf`. Writing two bytes per texel (intensity,
// alpha) is the IA16 layout and makes the importer read every second byte as a
// texel, which turns each glyph row into two garbled texture rows.
#define CN_IA8_BYTES (CN_GLYPH_W * CN_GLYPH_H)

// One tile per baked glyph, decoded on first use. That is 1061 * 256 = 271 KB
// of BSS, which is cheap -- and the fixed address matters: the renderer's
// texture cache is keyed on the source address alone (gfx_texture_cache_lookup
// compares addr/fmt/siz and nothing else), so a slot that gets recycled for a
// different character would keep serving the *previous* glyph forever.
static u8 sCnGlyphIA8[CN_GLYPH_COUNT][CN_IA8_BYTES];
static u8 sCnGlyphDecoded[CN_GLYPH_COUNT];

// Expand one 16x16 1bpp glyph (32 bytes, row-major MSb-first) into a 16x16 IA8
// tile. A set pixel becomes 0xFF (intensity 15, alpha 15): opaque white, so the
// existing IA text combine mode (G_CC_FADEA with the dialog env colour) tints
// it exactly like the vanilla font.
static void cn_decode_glyph(u32 index) {
    const u8 *src = &sCnGlyphs16x16[index * 32];
    u8 *dst = sCnGlyphIA8[index];
    u32 y, x;

    for (y = 0; y < CN_GLYPH_H; y++) {
        const u8 *row = src + y * CN_GLYPH_STRIDE;
        for (x = 0; x < CN_GLYPH_W; x++) {
            u8 bit = (row[x >> 3] >> (7 - (x & 7))) & 1;
            dst[y * CN_GLYPH_W + x] = bit ? 0xFF : 0x00;
        }
    }
    sCnGlyphDecoded[index] = 1;
}

// Returns a stable pointer to IA8 data for the given CN code, or NULL when the
// code is outside the baked glyph range.
u8 *cn_font_get_glyph(u16 code) {
    u32 index;

    if (code < CN_GLYPH_FIRST || code > CN_GLYPH_LAST) { return NULL; }
    index = code - CN_GLYPH_FIRST;
    if (index >= CN_GLYPH_COUNT) { return NULL; }

    if (!sCnGlyphDecoded[index]) { cn_decode_glyph(index); }
    return sCnGlyphIA8[index];
}

// --- Rendering --------------------------------------------------------------

// Ambient texture scale for builds that render text at less than 1:1. Used to
// hand the scale back to the engine after a dialog glyph forces it to 0xFFFF.
#if defined(VERSION_JP) || defined(VERSION_SH)
#define CN_TEXT_SCALE_DEFAULT 0x8000
#else
#define CN_TEXT_SCALE_DEFAULT 0xFFFF
#endif

// Our own quad, sized for a full-width CJK glyph (16x16). The engine's
// vertex_ia8_char is 16x8 and static to bin/segment2.c, so it cannot be reused.
// This mirrors the US vertex_ia8_char layout with the height doubled.
//
// Texture coordinates are *not* texels: gfx_pc turns a vertex texcoord into a
// UV with
//
//     U = tc * texture_scaling_factor >> 16      (gfx_sp_vertex)
//     u = (U - uls * 8) / 32                     (buf_vbo assembly)
//     uv = u / tex_width                         where tex_width = (lrs + 4) / 4
//
// With the US/JP dialog scale of ~1.0 and a 16-texel-wide tile this means
// tc = texel * 32, i.e. 16 texels -> 512. (The Japanese vanilla quad says 512
// for an 8-texel texture only because it renders at scale 0.5; copying its
// numbers verbatim doubles every coordinate and smears the glyph.)
//
// IMPORTANT: in menu space +y points UP, so this quad's y = 16 edge is the TOP
// of the glyph on screen. Hence texture row 0 must sit at y = 16, i.e. t runs
// 512 -> 0 as y goes 0 -> 16. Together with (x,y) -> s = 32*x this makes the
// quad an identity mapping of the glyph bitmap, so the bake tables must store
// characters TOP ROW FIRST (see gen_cn_glyphs.py).
//
// This was the wrong way round until 2026-10-06, when every rendered character
// came out upside down in-game. Two independent checks pinned the cause on the
// data, not on these coordinates: with this identity mapping the rendered image
// IS the stored bitmap, and the stored ！ had its long stem at the bottom with
// the dot above it, while the stored 。 sat top-left instead of lower-left.
// Note that flipping `t` here would also have "fixed" the symptom while leaving
// the layout wrong for anyone reading the tables -- do not do that.
//
// Reference: the official CN vertex in
// /home/toad/sm64decomp-cn/bin/segment2.c:11874 (VERSION_CN) draws 8x16 halves
// with s bound to y and t bound to x because it samples each 16x8 i1 tile
// transposed; we bake a whole 16x16 cell and draw it untransposed instead.
static const Vtx sCnTextQuad[] = {
    {{{     0,      0,      0}, 0, {     0,    512}, {0xff, 0xff, 0xff, 0xff}}},
    {{{    16,      0,      0}, 0, {   512,    512}, {0xff, 0xff, 0xff, 0xff}}},
    {{{    16,     16,      0}, 0, {   512,      0}, {0xff, 0xff, 0xff, 0xff}}},
    {{{     0,     16,      0}, 0, {     0,      0}, {0xff, 0xff, 0xff, 0xff}}},
};

// Shared by both draw paths below. Kept as one list so the dialog and menu
// renderers can never drift apart on tile geometry.
//
// Tile geometry notes (these are easy to get subtly wrong and the failure mode
// is a smear rather than a crash):
//   * gsDPSetTile's 4th argument is the *line size in 64-bit words*, not texels.
//     A 16-texel-wide G_IM_SIZ_8b row is 16 bytes = 2 words, so the render tile
//     must say 2. Saying 1 makes the sampler wrap every 8 texels, which is what
//     produced the "long stretched line" garbage instead of glyphs.
//   * The load block must cover 16*16 = 256 texels and is loaded with the
//     *load* tile, whose line size stays 0 (unused for G_TX_LOADTILE).
//   * The engine's own font is 8x16, so its reference numbers (line size 1,
//     tile size 8) cannot be copied verbatim for a 16-wide cell.
static void cn_setup_glyph_tile(void) {
    gDPSetTile(gDisplayListHead++, G_IM_FMT_IA, G_IM_SIZ_8b, 0, 0, G_TX_LOADTILE, 0, G_TX_CLAMP, 4, G_TX_NOLOD, G_TX_CLAMP, 4, G_TX_NOLOD);
    gDPLoadSync(gDisplayListHead++);
    gDPLoadBlock(gDisplayListHead++, G_TX_LOADTILE, 0, 0, (CN_GLYPH_W * CN_GLYPH_H) - 1, CALC_DXT(CN_GLYPH_W, G_IM_SIZ_8b_BYTES));
    gDPSetTile(gDisplayListHead++, G_IM_FMT_IA, G_IM_SIZ_8b, 2, 0, G_TX_RENDERTILE, 0, G_TX_CLAMP, 4, G_TX_NOLOD, G_TX_CLAMP, 4, G_TX_NOLOD);
    gDPSetTileSize(gDisplayListHead++, 0, 0, 0, (CN_GLYPH_W - 1) << G_TEXTURE_IMAGE_FRAC, (CN_GLYPH_H - 1) << G_TEXTURE_IMAGE_FRAC);
}

// Draw a CN glyph at the current dialog cursor.
//
// This is the *vertex* path: it emits sCnTextQuad and lets the caller's running
// cursor matrix place it. See cn_draw_glyph_rect() for the alternative.
//
// The texture scale is set explicitly because our texcoord numbers assume a
// scale of ~1.0, and whatever dl_ia_text_begin happened to leave behind is not
// ours to rely on (the Japanese build renders dialogs at 0.5). It is restored
// afterwards so the vanilla characters that share the string are unaffected.
void render_cn_char(u16 code) {
    u8 *glyph;

    // The 0x00xx range is bit-identical to the vanilla single-byte font, so
    // draw it with the engine's own renderer. Our baked CJK table has no
    // coverage for digits, letters, arrows, button icons or quotes, and asking
    // for it would produce blank cells.
    if (cn_glyph_is_vanilla(code)) {
        render_generic_char(cn_glyph_vanilla_byte(code));
        return;
    }

    glyph = cn_font_get_glyph(code);
    if (glyph == NULL) {
        // Unknown code: draw nothing rather than a misleading '?'. This is the
        // case for unused FF xx escapes, which carry no real glyph.
        return;
    }

    gDPPipeSync(gDisplayListHead++);
    gDPSetTextureImage(gDisplayListHead++, G_IM_FMT_IA, G_IM_SIZ_8b, 1, VIRTUAL_TO_PHYSICAL(glyph));
    cn_setup_glyph_tile();
    gSPTexture(gDisplayListHead++, 0xFFFF, 0xFFFF, 0, G_TX_RENDERTILE, G_ON);
    gSPVertexNonGlobal(gDisplayListHead++, sCnTextQuad, 4, 0);
    gSP2Triangles(gDisplayListHead++, 0, 1, 2, 0x0, 0, 2, 3, 0x0);
    gSPTexture(gDisplayListHead++, CN_TEXT_SCALE_DEFAULT, CN_TEXT_SCALE_DEFAULT, 0, G_TX_RENDERTILE, G_ON);
}

// Draw a CN glyph at an absolute menu position, the way the vanilla menu font
// does: a gSPTextureRectangle rather than a matrix-positioned vertex quad.
//
// Why this is NOT render_cn_char()+a translation matrix (which is how an
// earlier revision did it and which rendered the whole line in the wrong
// place): the two matrix-less and matrix-based paths use OPPOSITE vertical
// conventions.
//
//   * gSPTextureRectangle bypasses every matrix. gfx_draw_rectangle
//     (src/pc/gfx/gfx_pc.c) converts it directly to NDC with
//         ndc_y = -(y / (4 * HALF_SCREEN_HEIGHT)) + 1
//     so y = 0 is the TOP of the screen and y grows downwards. Every component
//     of print_menu_generic_string() -- including the vanilla 8x8 glyphs drawn
//     around this one -- lives in that frame.
//   * print_generic_string()/render_cn_char() go through the modelview matrix
//     set up by create_dl_ortho_matrix(), whose guOrtho(0, SCREEN_HEIGHT) maps
//     y = 0 to the BOTTOM. Its own multi-line handling proves it: each newline
//     re-anchors at `y - lineNum * MAX_STRING_WIDTH`, i.e. later lines get a
//     SMALLER y, which is what "further down the screen" means when +y is up.
//
// Feeding a top-down menu y into that matrix puts the glyph roughly at its
// mirror position, well away from the sibling vanilla text. Drawing a straight
// rectangle here keeps one single convention for the whole line, and makes the
// code independent of whatever the modelview happens to hold.
//
// The texture scale is deliberately left alone: the vanilla menu glyphs already
// rely on the ambient scale being ~1.0 (US dl_ia_text_begin sets
// gsSPTexture(0xFFFF, 0xFFFF) and nothing between it and here changes it), so
// our 16x16 cell samples 1:1 exactly like their 8x8 does. Setting it here and
// restoring CN_TEXT_SCALE_DEFAULT afterwards would be a no-op for US but could
// clobber a different value on other builds.
void cn_draw_glyph_rect(s32 x, s32 y, u16 code) {
    u8 *glyph = cn_font_get_glyph(code);

    if (glyph == NULL) {
        return;
    }

    gDPPipeSync(gDisplayListHead++);
    gDPSetTextureImage(gDisplayListHead++, G_IM_FMT_IA, G_IM_SIZ_8b, 1, VIRTUAL_TO_PHYSICAL(glyph));
    cn_setup_glyph_tile();
    gSPTextureRectangle(gDisplayListHead++,
                        x << 2, y << 2,
                        (x + CN_GLYPH_W) << 2, (y + CN_GLYPH_H) << 2,
                        G_TX_RENDERTILE, 0, 0, 1 << 10, 1 << 10);
}

f32 cn_char_width(u16 code) {
    // Codes served by the vanilla 8px font (0x00xx, plus the bit-15
    // equivalents) advance by the vanilla width, not a full CJK cell.
    if (cn_glyph_is_vanilla(code)) {
        return (f32)gDialogCharWidths[cn_glyph_vanilla_byte(code)];
    }
    return (f32)CN_GLYPH_W; // CJK glyphs are full-width.
}

// True when a CN glyph code should be drawn with the vanilla 8px font instead
// of our baked CJK glyph table.
//
// Only the 0x00xx space qualifies. Its second byte is bit-identical to a
// vanilla font index for every code the game uses:
//     0x00-0x23  digits and A-Z        (vanilla 0x00-0x23)
//     0x50-0x58  arrows and [A][B][C][Z][R]  (vanilla 0x50-0x58)
//     0xF5,0xF6  open/close double quote     (vanilla 0xF5,0xF6)
//
// Everything from 0x0100 up lives in the ROM's CJK table and must be drawn
// from it. In particular 0x0450-0x0453 (Ｓ Ｔ Ａ Ｒ) and 0x050F (－) do have
// real full-width bitmaps there -- the pause menu's "START" label is drawn in
// those -- so routing them to the narrow ASCII letters (as an earlier revision
// did) is visibly wrong.
bool cn_glyph_is_vanilla(u16 code) {
    u8 lo = (u8)(code & 0xFF);

    if (code >= 0x0100) { return false; }

    if (lo <= 0x23) { return true; }   // digits, A-Z
    if (lo >= 0x50 && lo <= 0x58) { return true; } // arrows, button icons
    if (lo == 0xF5 || lo == 0xF6) { return true; } // quotes
    return false;
}

// The vanilla font byte a CN code should be drawn as. Only reachable for the
// 0x00xx space, where the two encodings agree byte for byte.
u8 cn_glyph_vanilla_byte(u16 code) {
    return (u8)(code & 0xFF);
}

// --- Coloured CJK title font (iQue "HUD" font) -------------------------------
//
// A second, unrelated typeface. Where everything above is monochrome IA8 fed
// through the dialog combine mode, this is 124 16x16 RGBA16 cells with baked-in
// vertical gradients and drop shadows, and it is what the iQue release uses for
// its fixed screen titles (暂停 / 恭喜发财 / 最高分 / 马里奥 / ...).
//
// Do not confuse it with the IA8 table: they are different designs of the same
// characters. Matching the coloured cells against cn_glyphs_16x16.h by IoU
// peaks at 0.43, i.e. no better than chance, so there is no way to synthesise
// one from the other -- the real bitmaps have to be shipped.
//
// The codes are single bytes 0x3A-0x3A+123, indexed directly. They have
// nothing to do with the two-byte CN token encoding: 0x86 here is 暂, while
// 0x86 as the second byte of a CN token is an unrelated CJK glyph.

// Real iQue data. Generated by .workbuddy/gen_cn_hud_glyphs.py.
#include "cn_data/cn_hud_glyphs_rgba16.h"

// One dense RGBA16 cell per code, expanded from the run list on first use.
//
// A fixed slot per code is required, not merely convenient: gfx_pc's texture
// cache (gfx_texture_cache_lookup) keys on the source address alone, so a
// shared scratch buffer would make a recycled address keep serving whichever
// glyph was uploaded last. 124 * 512 bytes = 63 KB of BSS.
//
// This is a *byte* array, not a u16 array, and that is load-bearing.
// gfx_pc's import_texture_rgba16() reads a texel as
//     col16 = (addr[2*i] << 8) | addr[2*i + 1];
// i.e. big-endian, the same order the MIO0 segment stores the ROM copy in.
// Writing a host-order u16 here therefore byte-swaps every texel: the glyph
// still has the right outline, but its colour channels come out scrambled --
// and because RGBA5551's alpha bit is bit 0, the swap also moves half the
// alphas, which is what turned the title into coloured noise. Always store the
// high byte first.
static u8 sCnHudDense[CN_HUD_COUNT][CN_HUD_TEXELS * 2];
static u8 sCnHudDenseValid[CN_HUD_COUNT];

u8 *cn_font_get_hud_glyph(u8 code) {
    u32 index;
    const struct CnHudGlyph *g;
    u32 run, texel;

    if (code < CN_HUD_FIRST || code > CN_HUD_LAST) { return NULL; }
    index = (u32)code - CN_HUD_FIRST;

    if (!sCnHudDenseValid[index]) {
        u8 *dst = sCnHudDense[index];
        for (texel = 0; texel < CN_HUD_TEXELS * 2; texel++) { dst[texel] = 0; }

        g = &sCnHudGlyphs[index];
        for (run = 0; run < g->runCount; run++) {
            const struct CnHudRun *r = &sCnHudRuns[g->firstRun + run];
            u16 colour = r->colour;
            u32 end = (u32)r->start + r->len;
            // The generator cannot emit a run past the cell, but clamp anyway:
            // this buffer is written by index and an overflow would corrupt the
            // neighbouring glyph rather than merely drawing garbage.
            if (end > CN_HUD_TEXELS) { end = CN_HUD_TEXELS; }
            for (texel = r->start; texel < end; texel++) {
                dst[texel * 2 + 0] = colour >> 8;
                dst[texel * 2 + 1] = colour & 0xFF;
            }
        }
        sCnHudDenseValid[index] = 1;
    }
    return sCnHudDense[index];
}

// Tile setup for a 16x16 RGBA16 cell.
//
// These numbers are not free choices: they are the official
// dl_rgba16_load_tex_block (bin/segment2.c, vaddr 0x0200ED38), which is the
// display list iQue itself uses to blit these very cells -- line size 4 (a
// 16-texel RGBA16 row is 32 bytes = 4 64-bit words), mask/maskt 4, tile size
// (16-1) << G_TEXTURE_IMAGE_FRAC, and a load block of 16*16 texels.
//
// The mask is 4 even though RGBA16 carries 5 bits per channel; the F3DEX bit
// field counts differently for this format and the engine's own HUD font relies
// on 4, so 5 would resample the glyph.
//
// The *load* tile wraps and the *render* tile clamps -- that asymmetry is in
// the official display list too. Using WRAP on the render tile (as this
// function used to) makes column 16 of the rect sample column 0 again, which
// shows up as a one-texel seam / doubled edge on the right of every cell.
static void cn_setup_hud_tile(void) {
    gDPSetTile(gDisplayListHead++, G_IM_FMT_RGBA, G_IM_SIZ_16b, 0, 0, G_TX_LOADTILE, 0, G_TX_WRAP | G_TX_NOMIRROR, 4, G_TX_NOLOD, G_TX_WRAP | G_TX_NOMIRROR, 4, G_TX_NOLOD);
    gDPLoadSync(gDisplayListHead++);
    gDPLoadBlock(gDisplayListHead++, G_TX_LOADTILE, 0, 0, CN_HUD_TEXELS - 1, CALC_DXT(CN_HUD_TEXELS, G_IM_SIZ_16b_BYTES));
    gDPSetTile(gDisplayListHead++, G_IM_FMT_RGBA, G_IM_SIZ_16b, 4, 0, G_TX_RENDERTILE, 0, G_TX_CLAMP, 4, G_TX_NOLOD, G_TX_CLAMP, 4, G_TX_NOLOD);
    gDPSetTileSize(gDisplayListHead++, 0, 0, 0, (CN_GLYPH_W - 1) << G_TEXTURE_IMAGE_FRAC, (CN_GLYPH_H - 1) << G_TEXTURE_IMAGE_FRAC);
}

// Blit one 16x16 RGBA16 cell.
//
// `copy` says which RDP cycle mode the *caller's* display list is in, and it
// changes both the rectangle's right/bottom edge and dsdx. This is not
// cosmetic: gfx_pc's gfx_dp_texture_rectangle() divides dsdx by 4 in
// G_CYC_COPY (and grows the rect by one pixel to compensate), and does neither
// outside COPY. The official iQue code therefore contains two different
// spellings of the same 1-texel-per-pixel blit:
//
//   G_CYC_COPY, dl_hud_img_begin .... render_textrect()        +15, dsdx 4<<10
//   1-cycle,     dl_rgba16_text_begin  print_hud_lut_string()  +16, dsdx 1<<10
//
// Both callers of this helper exist in this port: the coloured pause / hi-score
// titles go through dl_rgba16_text_begin (1-cycle), while the title screen's
// "按" goes through render_text_labels() under dl_hud_img_begin (COPY).
// Hardcoding either value gives one of them a 4x horizontal stretch -- the
// other one is what made the pause titles (or the intro prompt) unreadable.
static void cn_draw_hud_cell(s32 x, s32 y, u8 code, bool copy) {
    u8 *glyph = cn_font_get_hud_glyph(code);

    if (glyph == NULL) {
        return;
    }

    gDPPipeSync(gDisplayListHead++);
    gDPSetTextureImage(gDisplayListHead++, G_IM_FMT_RGBA, G_IM_SIZ_16b, 1, VIRTUAL_TO_PHYSICAL(glyph));
    cn_setup_hud_tile();
    gSPTexture(gDisplayListHead++, 0xFFFF, 0xFFFF, 0, G_TX_RENDERTILE, G_ON);
    // HUD space: y grows downward from the top of the screen, because
    // gfx_draw_rectangle() maps a rectangle straight to NDC.
    gSPTextureRectangle(gDisplayListHead++,
                        x << 2, y << 2,
                        (x + CN_GLYPH_W - (copy ? 1 : 0)) << 2,
                        (y + CN_GLYPH_H - (copy ? 1 : 0)) << 2,
                        G_TX_RENDERTILE, 0, 0, copy ? (4 << 10) : (1 << 10), 1 << 10);
}

// 1-cycle variant: the coloured HUD titles (pause / hi-score / congratulations)
// are drawn between dl_rgba16_text_begin and dl_rgba16_text_end, exactly like
// the official print_hud_lut_string().
void cn_draw_hud_glyph_rect(s32 x, s32 y, u8 code) {
    cn_draw_hud_cell(x, y, code, false);
}

// One glyph cell of horizontal advance. iQue uses a full 16px step for every
// code >= 0x3A (see print_hud_lut_string()'s `str[pos] < 0x3A ? +12 : +16`).
#define CN_HUD_ADVANCE 16
#define CN_HUD_LINE_HEIGHT 16

s32 cn_draw_hud_title(s32 x, s32 y, const u8 *str) {
    s32 pos = 0;
    s32 curX = x;
    s32 curY = y;
    s32 minX = x;
    s32 maxX = x;

    // A single line of a title is at most a dozen glyphs; the cap only exists so
    // a malformed pointer cannot spin here forever.
    for (s32 guard = 0; guard < 256; guard++) {
        u8 c = str[pos];

        if (c == 0xFF) { break; }               // end of string
        if (c == 0xFE) {                        // newline: start a new line at x
            if (curX > maxX) { maxX = curX; }
            curX = x;
            curY += CN_HUD_LINE_HEIGHT;
            pos++;
            continue;
        }

        // Codes below 0x3A are the ASCII HUD font and are not part of this
        // typeface. Skipping them (rather than drawing a wrong cell) keeps a
        // mixed string readable instead of turning stray ASCII into garbage,
        // and still advances so the layout stays close to iQue's.
        if (c < CN_HUD_FIRST) {
            curX += CN_HUD_ADVANCE;
            pos++;
            continue;
        }

        cn_draw_hud_glyph_rect(curX, curY, c);
        curX += CN_HUD_ADVANCE;
        pos++;
    }

    if (curX > maxX) { maxX = curX; }
    (void)minX;
    return maxX - x;
}

// --- Pseudo-glyphs built from several cells ---------------------------------
//
// A few iQue "characters" are not a single 16x16 cell. The official renderer
// recognises their byte in the text-label buffer and blits a small block of
// ordinary HUD cells instead -- see /home/toad/sm64decomp-cn/src/game/print.c,
// render_text_labels(), which special-cases 0xB0 and 0xC0. The ROM's own 0xB0
// cell is therefore NOT the finished glyph (it holds ~51 opaque texels, a
// fragment); the readable character only exists once the quarters are laid out.
//
// We reproduce the 0xB0 case because the title screen needs it: iQue's
// "按 Start" prompt draws 按 this way, from cells 0x92/0x93 (top row) and
// 0x94/0x95 (bottom row):
//
//     +------+------+        +---+---+
//     | 0x92 | 0x93 |   ->   |   |   |   "按"
//     +------+------+        +---+---+
//     | 0x94 | 0x95 |        |   |   |
//     +------+------+        +---+---+
//
// (The 0xC0 eight-cell block belongs to the file-select screen and is left out
// until something actually emits it.)
s32 cn_draw_hud_pseudo(s32 x, s32 y, u8 code) {
    if (code != 0xB0) {
        return 0;
    }

    // COPY: this is only ever called from render_text_labels(), which wraps the
    // label pass in dl_hud_img_begin (G_CYC_COPY). That is also why the
    // official 0xB0 branch uses render_textrect()'s 4<<10 spelling.
    cn_draw_hud_cell(x,      y,      0x92, true);
    cn_draw_hud_cell(x + 16, y,      0x93, true);
    cn_draw_hud_cell(x,      y + 16, 0x94, true);
    cn_draw_hud_cell(x + 16, y + 16, 0x95, true);
    return 32;
}

// --- CN string identification -----------------------------------------------
//
// The two encodings are byte-for-byte ambiguous (see cn_read_token), so the
// walkers have to be *told* which one a string uses. Rather than thread a flag
// through a dozen call sites, we ask the one authoritative question: is this
// pointer one of the strings the pack installed?
//
// There are three sources of CN text:
//   1. seg2_course_name_table / seg2_act_name_table (course + act names)
//   2. the dialog entries' ->str            (dialog text)
//   3. the cn_dialog_registry mirror        (needed because a Lua override or
//      apply_cn_text_pack() may have swapped ->str out from under us)
//
// Everything else -- HUD strings, stack buffers, LUT icon strings -- is
// vanilla and must be walked byte-wise.
bool cn_is_cn_string(const u8 *str) {
#if defined(SM64COOPDX_CN_TEXT)
    extern u8 *seg2_course_name_table[];
    extern u8 *seg2_act_name_table[];
    extern const u8 *const cn_dialog_registry[];
    u32 i;

    if (str == NULL) { return false; }

    // Only meaningful when the pack is actually installed.
    if (!gCnTextPackActive) { return false; }

    // Fixed UI labels first: 22 pointer compares, and they are the most common
    // CN string on screen (every INGAME_TEXT_COPY() site). The order matters --
    // the course-name test below has to walk tokens and is the only expensive
    // one, so everything cheaper gets to short-circuit before it.
    //
    // These are shared read-only arrays (so two labels with the same text are
    // literally the same pointer), which also makes this loop a no-op when the
    // pack is off -- cn_label_get() then returns NULL and the label stays the
    // vanilla ROM string.
    for (i = 0; i < CN_LABEL_COUNT; i++) {
        if (str == cn_label_table[i]) { return true; }
    }

    // Dialogs: the registry holds every CN buffer we ever compiled in, so a
    // pointer matches even after the live entry has been repointed.
    for (i = 0; i < 4096 && cn_dialog_registry[i] != NULL; i++) {
        if (str == cn_dialog_registry[i]) { return true; }
    }

    // Act (star) names carry no prefix and are always walked from their base.
    for (i = 0; i < 260; i++) {
        const u8 *p = seg2_act_name_table[i];
        if (p == NULL) { break; }
        if (str == p) { return true; }
    }

    // Course names are the one case where the pointer we are handed is NOT the
    // base of the buffer. The iQue entries are
    //     [9E][num][9E]  (vanilla 3-byte prefix, other callers pass `+ 3`)
    //     [FF 9E]        (U+3000)
    //     [00 nn]...     (full-width course number, 1-2 tokens)
    //     [FF 9E]        (U+3000)
    //     <the name>
    // and cn_strip_course_name_decoration() returns a pointer to <the name>,
    // i.e. base + 3 + 2k for some k. A plain `== p || == p + 3` test misses
    // exactly that pointer, so the pause menu fell back to the byte-wise
    // vanilla walk and drew 炸弹王国's four 0x01 lead bytes as four "1"s -- the
    // "1111" course name.
    //
    // So accept any *token boundary* of a CN course name, found by walking the
    // token stream from the base. This is exact (every byte inside one of these
    // arrays genuinely is CN text) and, unlike a length table or a pointer
    // registry, it needs no generated side data and cannot go stale when
    // apply_cn_text_pack() re-points the table.
    //
    // Two bounds keep it cheap and safe. `q < str` stops as soon as the walk
    // passes the pointer being tested (q only ever grows), so an unrelated
    // pointer -- a stack buffer, a HUD string -- costs one comparison per
    // table slot instead of a full walk. `limit` caps the walk at 32 bytes,
    // the longest iQue entry (30) rounded up, so a slot that somehow points at
    // a single-0xFF ROM stub cannot walk past its own array.
    #define CN_COURSE_SCAN_BYTES 32
    for (i = 0; i < 26; i++) {
        const u8 *p = seg2_course_name_table[i];
        if (p == NULL) { break; }
        if (str == p) { return true; }
        // `p + 3` is the form every caller that just wants past the vanilla
        // prefix uses (star select, the course-clear screen). It has to be
        // answered here, not left to the walk below.
        if (str == p + 3) { return true; }
        if (str < p + 3) { continue; }

        const u8 *q = p + 3;
        const u8 *const limit = p + 3 + CN_COURSE_SCAN_BYTES;
        while (q < str && q < limit) {
            CnToken tok = cn_read_token(q, 0, true);
            if (tok.kind == CN_TOKEN_END || tok.length <= 0) { break; }
            q += tok.length;
        }
        if (q == str) { return true; }
    }
    #undef CN_COURSE_SCAN_BYTES
#else
    (void)str;
#endif

    return false;
}

const u8 *cn_label_get(CNLabelId id) {
#if defined(SM64COOPDX_CN_TEXT)
    extern const u8 *const cn_label_table[];

    if (!gCnTextPackActive) { return NULL; }
    if ((u32)id >= CN_LABEL_COUNT) { return NULL; }

    return cn_label_table[id];
#else
    (void)id;
    return NULL;
#endif
}

// --- CN token reading -------------------------------------------------------

// iQue/CN text is a stream of two-byte tokens (see cn_font.h). Decoding them
// here keeps every walker in agreement about where a token ends, which matters
// because the vanilla renderers treat every 0xFF as end-of-string.
//
// `cn` says whether the caller knows this is a CN string. It has to be passed
// in because the two encodings are byte-for-byte ambiguous: vanilla stores "1"
// as the single byte 0x01, and CN stores "的" as the pair 0x01 0x01, so no
// amount of looking at the bytes can tell them apart. Vanilla strings (HUD
// text, and the {0xFA,0x9E,...} star-icon strings that print_generic_string
// receives) must be walked with cn == false or their integers get eaten as CJK
// glyphs -- that is exactly what produced the "00000000000".
CnToken cn_read_token(const u8 *str, s32 index, bool cn) {
    CnToken tok;
    u8 lead;

    tok.kind = CN_TOKEN_NONE;
    tok.code = 0;
    tok.length = 1;

    if (str == NULL || !cn) { return tok; }

    lead = str[index];

    // ASCII glyph, always two bytes: 0x00 <char>. 0x00 0x00 = '0',
    // 0x00 0x01 = '1', ...
    //
    // 0x00 0x00 must be decoded as '0' like any other ASCII glyph. Treating it
    // as "possibly an unwritten byte" (as this function used to) desynchronises
    // the walker by one byte: the caller falls back to the single-byte path,
    // draws 0x00, then re-enters at the *second* 0x00, reads it together with
    // the next token's lead byte as a phantom glyph and consumes 16 extra
    // pixels. On the pause menu that showed up as a wide gap inside
    // "10 雪人王国" (the course number ends in a 0), and it would corrupt the
    // rest of any string containing a zero. CN strings always end with
    // 0xFF 0xFF, so there is no half-filled-buffer case to protect here.
    //
    // These are NOT wide glyphs, despite what an earlier comment here claimed.
    // The official CN build draws every strChar < 0x0100 with the plain vanilla
    // render_generic_char() and the vanilla width (see its default branch in
    // /home/toad/sm64decomp-cn/src/game/ingame_menu.c). charmap.txt agrees:
    // '0' and the full-width '０' are both 0x0000, so iQue never distinguished
    // the two forms. cn_glyph_is_vanilla()/cn_char_width() reproduce that.
    if (lead == 0x00) {
        tok.kind = CN_TOKEN_GLYPH;
        tok.code = ((u16)lead << 8) | (u16)str[index + 1];
        tok.length = 2;
        return tok;
    }

    // CJK glyph, always two bytes. 0x01-0x04 pair with every low byte, so there
    // is no sub-range to test for.
    if (lead >= 0x01 && lead <= 0x05) {
        tok.kind = CN_TOKEN_GLYPH;
        tok.code = ((u16)lead << 8) | (u16)str[index + 1];
        tok.length = 2;
        return tok;
    }

    if (lead == 0xFF) {
        u8 second = str[index + 1];
        switch (second) {
            case 0xFE: tok.kind = CN_TOKEN_NEWLINE; break;
            case 0x9E: tok.kind = CN_TOKEN_SPACE;   break;
            case 0xFF: tok.kind = CN_TOKEN_END;     break;
            default:
                // Any other FF xx escape: treat as a glyph so the walker still
                // advances by exactly two bytes. The glyph table lookup fails
                // and render_cn_char() draws nothing, which is right for an
                // unused escape.
                tok.kind = CN_TOKEN_GLYPH;
                tok.code = ((u16)lead << 8) | (u16)second;
                break;
        }
        tok.length = 2;
        return tok;
    }

    // A vanilla single-byte LUT glyph embedded in CN data: the star icons
    // DIALOG_CHAR_STAR_FILLED (0xFA) and DIALOG_CHAR_STAR_OPEN (0xFD) are the
    // only realistic cases. Return NONE so the caller draws them with the
    // vanilla renderer. Everything else here (0x06-0xF9, 0xFB-0xFC, 0xFE) is
    // likewise vanilla, and this is also the guard that stops a vanilla buffer
    // from being walked as CN.
    return tok;
}

